-- ORDER BY
SELECT * FROM emp1 ORDER BY empid DESC;


SELECT empname, sal FROM emp1 ORDER BY sal DESC OFFSET 2 ROWS FETCH NEXT 1 ROWS ONLY;

-- RANK
SELECT RANK() OVER(ORDER BY sal DESC), empname, sal FROM emp1;

-- Row_number
SELECT ROW_NUMBER() OVER(ORDER BY sal DESC), RANK() OVER(ORDER BY sal DESC), empname, sal FROM emp1;

-- DENSE_RANK
SELECT DENSE_RANK() OVER(ORDER BY sal DESC), RANK() OVER(ORDER BY sal DESC), empname, sal FROM emp1;

-- Partition by
SELECT ROW_NUMBER() OVER(partition by dept ORDER BY sal DESC),empname, dept, sal  from emp1;

SELECT ROW_NUMBER() OVER(partition by dept ORDER BY sal DESC) as rank ,empname, dept, sal  from emp1 where rank = 1;


-- write a query to find top salary holder in each dept only
SELECT empname, dept, sal  FROM (
SELECT empname, dept, sal, ROW_NUMBER() OVER(partition by dept ORDER BY sal DESC) )from emp1 ;


-- Aggragate functions along with group by
