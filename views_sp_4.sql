CREATE OR REPLACE PROCEDURE CALCULATOR_SP(num1 float, num2 float)
language plpgsql
as $$
declare
	addsp float := num1 + num2;
	subsp float := num1 - num2;
	multisp float := num1 * num2;
begin
raise notice 'addition of tow number =%',addsp;
raise notice 'substraction of tow number =%',subsp;
raise notice 'multiplaction of tow number =%',multisp;
end;$$

call CALCULATOR_SP(10,20);


-- loop
CREATE OR REPLACE PROCEDURE multiplaction(num1 int )
language plpgsql
as $$
declare
	n1 int :=1;
	val1 int :=0;
begin
While (n1 <= 10) loop
	val1 = num1 * n1;
	raise notice '% * % = %', num1,n1,val1;
	n1 := n1+1;
end loop;
end;$$

call multiplaction(24)




