CREATE OR REPLACE PROCEDURE sp_grd(per float)
language plpgsql
as $$
declare
	gread varchar(100):=' ';
begin
if (per >= 75) then 
	gread := 'DISTENCTION';
elseif (per >= 60) then 
	gread := 'FIRST CLASS';
elseif (per >= 50) then 
	gread := 'SECOND CLASS';
elseif (per >= 35) then 
	gread := 'THIRD CLASS';
else 
	gread := 'FAIL!';
end if;
end;$$


CREATE table students1 (
roll_num int primary key,
sname varchar(100),
eng_marks int ,
scn_marks int ,
math_marks int,
total_marks int  ,
percentage float,
gread varchar(100)
);

CREATE  OR REPLACE PROCEDURE cm()
language plpgsql
as $$
declare
total_marks int;
percentage float ;
gread varchar(100);
begin 
	update students1
	set
		total_marks = eng_marks + scn_marks + math_marks,
		percentage = total_marks/3;

		update students1
    	set 
		gread = CASE 
		When percentage >= 90 Then 
		'A'
		When percentage >= 60 Then 
		'B'
		When percentage >= 35 Then 
		'C'
		ELSE 'F'
		END;
	raise notice 'Total marks , Percentage and Grades have been calculated and updated';
END;$$

