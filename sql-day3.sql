-- rollup
-- for first column
SELECT gender , dept, count (empid) AS empcount 
	from emp1 group by ROLLUP (gender, dept); 

-- cube 
-- both the column
SELECT gender , dept, count (empid) AS empcount 
	from emp1 group by cube (gender, dept);




